const DICTS: Record<Locale, Dict> = { 'zh-CN': zhCN, en, 'zh-TW': zhTW };

export type TFn = (key: string, params?: Record<string, string | number>) => string;

export function makeT(locale: Locale): TFn {
  const dict = DICTS[locale] ?? zhCN;
  return (key, params) => {
    let s = dict[key] ?? zhCN[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

/* ---- React binding (standalone app: zh-CN by default) ---- */

const LocaleContext = React.createContext<Locale>('zh-CN');

export function LocaleProvider({
  locale = 'zh-CN',
  children,
}: {
  locale?: Locale;
  children: React.ReactNode;
}) {
  return React.createElement(LocaleContext.Provider, { value: locale }, children);
}

export function useLocale(): Locale {
  return React.useContext(LocaleContext);
}

export function useT(): TFn {
  const locale = useLocale();
  return React.useMemo(() => makeT(locale), [locale]);
}

/* Non-hook translator for one-off / non-component usage (fixed zh-CN). */
export const t: TFn = makeT('zh-CN');
